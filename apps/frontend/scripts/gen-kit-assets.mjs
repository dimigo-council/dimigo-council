// AI-written
// Turns the JSON written by the "DIMI Kit Export" Figma plugin into kit assets:
//   src/dimi-ui-kit/icons.generated.ts   — one named export per Icon variant (24×24, filled with currentColor)
//   src/dimi-ui-kit/brand/*.svg          — every Logo/Symbol variant, as exported
// Usage: node scripts/gen-kit-assets.mjs <kit-assets.json>
import fs from 'node:fs';
import path from 'node:path';

const input = process.argv[2];
if (!input) throw new Error('Pass the path of the kit-assets.json file.');
const kit = JSON.parse(fs.readFileSync(input, 'utf8'));
const root = new URL('../src/dimi-ui-kit/', import.meta.url).pathname;

const variantValue = (name, key) =>
  name
    .split(',')
    .map((s) => s.trim().replace(/\u0008/g, ''))
    .find((s) => s.startsWith(key + '='))
    ?.slice(key.length + 1);

// Icons
const icons = kit['Icon'];
if (!icons) throw new Error('No "Icon" set in the export.');
const entries = Object.entries(icons)
  .map(([variant, svg]) => {
    const name = variantValue(variant, 'Type');
    const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
    if (!name || ds.length !== 1)
      throw new Error(`Unexpected icon "${variant}" (${ds.length} paths)`);
    return [name, ds[0]];
  })
  .sort(([a], [b]) => a.localeCompare(b));
// One named export per icon so the bundler keeps only the icons a page imports.
const ident = (n) =>
  'icon' +
  n
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
const seen = new Set();
for (const [n] of entries) {
  const id = ident(n);
  if (seen.has(id)) throw new Error(`Duplicate icon identifier ${id}`);
  seen.add(id);
}
const ts = `// Generated by scripts/gen-kit-assets.mjs from DIMI UI KIT (Icon, ${entries.length} variants). Do not edit.
// Import only the icons you use, e.g. \`import { iconSearch } from './icons'\`.
import type { KitIcon } from './icon-type';

${entries.map(([n, d]) => `export const ${ident(n)}: KitIcon = { name: ${JSON.stringify(n)}, d: ${JSON.stringify(d)} };`).join('\n')}
`;
fs.writeFileSync(path.join(root, 'icons.generated.ts'), ts);

// Brand
const brandDir = path.join(root, 'brand');
fs.mkdirSync(brandDir, { recursive: true });
const brandIndex = {};
for (const [setName, variants] of Object.entries(kit)) {
  if (setName === 'Icon') continue;
  const base = setName.replace('/', '-').toLowerCase();
  for (const [variant, svg] of Object.entries(variants)) {
    const style = variantValue(variant, 'Style').toLowerCase();
    const size = variantValue(variant, 'Size');
    const file = `${base}-${style}-${size}.svg`;
    // Make mask/clip ids unique per file so several inline copies can share a page.
    const prefix = `${base}-${style}-${size}-`;
    const unique = svg
      .replace(/id="([^"]+)"/g, `id="${prefix}$1"`)
      .replace(/url\(#([^)]+)\)/g, `url(#${prefix}$1)`);
    fs.writeFileSync(path.join(brandDir, file), unique);
    (brandIndex[setName] ??= {})[`${style}/${size}`] = file;
  }
}
fs.writeFileSync(
  path.join(brandDir, 'index.json'),
  JSON.stringify(brandIndex, null, 2) + '\n',
);
console.log(
  `icons: ${entries.length}; brand: ${Object.entries(brandIndex)
    .map(([k, v]) => `${k} ${Object.keys(v).length}`)
    .join(', ')}`,
);
